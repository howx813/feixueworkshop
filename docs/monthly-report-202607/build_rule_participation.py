def make_doc(path, title, subtitle=""):
    doc = Document()
    for section in doc.sections:
        section.top_margin = Cm(3.0)
        section.bottom_margin = Cm(3.0)
        section.left_margin = Cm(2.8)
        section.right_margin = Cm(2.6)
    add_para = make_adder(doc)
    if title:
        add_para(title, font='黑体', size=20, bold=True,
                 align=WD_ALIGN_PARAGRAPH.CENTER, indent=False, space_after=4, line=32)
    if subtitle:
        add_para(subtitle, font='楷体', size=12,
                 align=WD_ALIGN_PARAGRAPH.CENTER, indent=False, space_after=14, line=24)
    doc._adder = add_para
    return doc


def make_adder(doc):
    def set_font(run, name_cn, size, bold=False):
        run.font.name = name_cn
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.color.rgb = RGBColor(0, 0, 0)
        r = run._element.rPr.rFonts
        r.set(qn('w:eastAsia'), name_cn)

    def add_para(text, font='仿宋', size=14, bold=False, align=None,
                 indent=True, space_after=6, line=26):
        p = doc.add_paragraph()
        pf = p.paragraph_format
        if align is not None:
            pf.alignment = align
        if indent:
            pf.first_line_indent = Pt(size * 2)
        pf.space_before = Pt(0)
        pf.space_after = Pt(space_after)
        pf.line_spacing_rule = WD_LINE_SPACING.EXACTLY
        pf.line_spacing = Pt(line)
        run = p.add_run(text)
        set_font(run, font, size, bold)
        return p
    return add_para


def h1(ap, text):
    ap(text, font='黑体', size=16, bold=True, indent=False, space_after=8, line=30)

def h2(ap, text):
    ap(text, font='楷体', size=14, bold=True, indent=False, space_after=4, line=26)

def body(ap, text):
    ap(text, font='仿宋', size=14, indent=True, space_after=4, line=26)


